def test_two_jobs_for_one_stl_do_not_collide(tmp_path: Path) -> None:
    """The clause the whole item exists for.

    One directory stands in for the printer's flat storage. Same part, same
    slicer numbers, two jobs: two files must survive.
    """
    storage = tmp_path / "printer-local"
    storage.mkdir()

    names = []
    for _ in range(2):
        job_dir = tmp_path / uuid.uuid4().hex
        job_dir.mkdir()
        result = name_gcode(a_result(job_dir), job_id=str(uuid.uuid4()), part="bracket")
        # Upload: the name it carries locally is the name it lands under.
        target = storage / result.gcode_path.name
        target.write_bytes(result.gcode_path.read_bytes())
        names.append(target.name)

    assert names[0] != names[1], "two jobs produced the same filename"
    assert len(list(storage.iterdir())) == 2, "one job overwrote the other"


def test_the_name_carries_the_job_id_and_the_part(tmp_path: Path) -> None:
    job_id = str(uuid.uuid4())
    result = name_gcode(a_result(tmp_path), job_id=job_id, part="corner-bracket")
    name = result.gcode_path.name

    assert job_id in name
    assert "corner-bracket" in name, "the part is not recognisable on the printer's screen"


def test_the_job_id_round_trips_out_of_the_filename() -> None:
    """Given a filename from `list_files`, the job id comes back."""
    for _ in range(200):
        job_id = str(uuid.uuid4())
        name = gcode_filename(
            job_id=job_id,
            part="bracket",
            print_time_s=4740,
            nozzle_mm=0.4,
            material="PLA",
            layer_height_mm=0.2,
        )
        assert job_id_from_filename(name) == job_id


def test_the_job_id_round_trips_through_a_printer_path() -> None:
    """The firmware reports `/local/<name>` in some frames and a bare name in others."""
    job_id = str(uuid.uuid4())
    name = gcode_filename(job_id=job_id, part="tee", print_time_s=850)
    assert job_id_from_filename(f"/local/{name}") == job_id


@pytest.mark.parametrize(
    "foreign",
    [
        "ECC_0.4_Benchy_PLA0.2_1h19m.gcode",  # Orca's own upload, no job id
        "plate_1.gcode",
        "something.gcode",
        "ECC_0.4_bracket_PLA0.2_14m_not-a-uuid.gcode",
        "ECC_0.4_bracket_PLA0.2_14m_deadbeef-dead-beef-dead-beefdeadbee.gcode",  # 11 tail
        "",
    ],
)
def test_files_this_project_did_not_name_return_none(foreign: str) -> None:
    """164 files were already on the printer. None of them are ours."""
    assert job_id_from_filename(foreign) is None


def test_a_foreign_file_containing_a_uuid_is_not_claimed_as_ours() -> None:
    """Only the last field before the extension is a job id.

    `job_id_from_filename` runs over `list_files` output, and 164 of those
    files were not written by this project. A uuid loose in the middle of
    somebody else's filename must not be reported as a job id — that would tie
    a print we did not start to a job we did, which is worse than not
    recognising it at all.

    (A uuid cannot reach the part field through `gcode_filename`, because
    `sanitize_part` truncates below 36 characters. These names are built by
    hand for that reason.)
    """
    decoy = str(uuid.uuid4())
    assert job_id_from_filename(f"ECC_0.4_{decoy}-v2_PLA0.2_1h19m.gcode") is None
    assert job_id_from_filename(f"backup_{decoy}_old.gcode") is None
    assert job_id_from_filename(f"{decoy}_copy.gcode") is None

    # And the same uuid in the job-id position still comes back.
    assert job_id_from_filename(f"ECC_0.4_tee_PLA0.2_14m_{decoy}.gcode") == decoy


