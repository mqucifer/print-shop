@pytest.mark.parametrize(
    "seconds,tag",
    [
        (45, "45s"),
        (850, "14m"),  # the tee fixture, measured
        (4740, "1h19m"),  # Orca's own example name
        (3600, "1h0m"),
        (0, "0s"),
        (97445, "1d3h"),
        (-5, "0s"),
    ],
)
def test_duration_tag(seconds: int, tag: str) -> None:
    assert duration_tag(seconds) == tag


@pytest.mark.parametrize(
    "raw,clean",
    [
        ("bracket", "bracket"),
        ("corner-bracket", "corner-bracket"),
        ("v2.1_final", "v2-1-final"),  # dot and underscore are structural
        ("my part (2)", "my-part-2"),
        ("café", "caf"),
        ("___", "part"),  # nothing usable left
        ("", "part"),
        ("-lead-and-trail-", "lead-and-trail"),
    ],
)
def test_sanitize_part(raw: str, clean: str) -> None:
    assert sanitize_part(raw) == clean


def test_a_long_part_name_is_truncated_but_still_recognisable() -> None:
    name = sanitize_part("a-very-long-descriptive-model-name-that-goes-on")
    assert len(name) <= MAX_PART_CHARS
    assert name.startswith("a-very-long")


def test_the_separator_never_appears_inside_a_field() -> None:
    """Underscore splits the name, so no field may contain one.

    If it could, the job id would not be the last underscore-delimited field
    and `job_id_from_filename` would be reading the wrong thing.
    """
    job_id = str(uuid.uuid4())
    name = gcode_filename(
        job_id=job_id,
        part="v2.1_final_rev_b",
        print_time_s=850,
        nozzle_mm=0.4,
        material="PLA_HF",
        layer_height_mm=0.2,
    )
    stem = name.removesuffix(".gcode")
    # ECC, nozzle, part, material+layer, duration, and the job id's own 5 parts.
    assert stem.split("_")[-1] == job_id
    assert job_id_from_filename(name) == job_id


def test_missing_slicer_settings_drop_their_segment_rather_than_failing() -> None:
    """A profile that omits a field must not fail an already-sliced job."""
    job_id = str(uuid.uuid4())
    name = gcode_filename(job_id=job_id, part="tee", print_time_s=850)
    assert name == f"ECC_tee_14m_{job_id}.gcode"
    assert job_id_from_filename(name) == job_id


def test_the_name_is_a_function_of_its_inputs_only() -> None:
    kwargs = {
        "job_id": "3f2a1c4e-9b7d-4f21-8a3e-1c5d7e9f0a2b",
        "part": "bracket",
        "print_time_s": 4740,
        "nozzle_mm": 0.4,
        "material": "PLA",
        "layer_height_mm": 0.2,
    }
    assert gcode_filename(**kwargs) == gcode_filename(**kwargs)  # type: ignore[arg-type]
    assert (
        gcode_filename(**kwargs)  # type: ignore[arg-type]
        == "ECC_0.4_bracket_PLA0.2_1h19m_3f2a1c4e-9b7d-4f21-8a3e-1c5d7e9f0a2b.gcode"
    )


