"""Specification for `src/slicer/naming.py`.

`BACKLOG.md` set the fitness function for this before it was built, and each
clause of it is a test here:

    two jobs submitted for the same STL produce two files, both present,
    neither overwriting the other; each name contains the job id and enough of
    the part name to be recognised on the printer's screen; and the name
    round-trips — given a filename from `list_files`, the job id can be
    recovered.

The collision test is the one that matters. It puts both files in a single
directory on purpose: the printer's internal storage is one flat namespace, so
a directory is the honest model of it. Two jobs landing on one name there means
the second print is of the first job's part.

The pure functions always run. One test slices for real and is marked `slicer`,
because the claim that nozzle/material/layer height can be read back out of the
G-code is a claim about Orca's output format, and only Orca can settle it.
"""

from __future__ import annotations

import os
import uuid
from pathlib import Path

import pytest

from print_shop.core.state import SliceResult
from print_shop.slicer.naming import (
    MAX_PART_CHARS,
    duration_tag,
    gcode_filename,
    job_id_from_filename,
    name_gcode,
    sanitize_part,
)
from print_shop.slicer.orca import SlicerProfiles, slice_model
from tests.fixtures import write_stl

ORCA = Path("/Applications/OrcaSlicer.app/Contents/MacOS/OrcaSlicer")
DATADIR = Path(os.path.expanduser("~/Library/Application Support/OrcaSlicer"))
_SYS = DATADIR / "system" / "Elegoo"
MACHINE = _SYS / "machine" / "ECC" / "Elegoo Centauri Carbon 0.4 nozzle.json"
PROCESS = _SYS / "process" / "ECC" / "0.20mm Standard @Elegoo CC 0.4 nozzle.json"
FILAMENT = _SYS / "filament" / "ECC" / "Elegoo PLA @ECC.json"

needs_orca = pytest.mark.skipif(
    not (ORCA.exists() and MACHINE.exists() and PROCESS.exists()),
    reason="OrcaSlicer or the Elegoo Centauri Carbon profiles are not installed",
)


def a_result(tmp_path: Path, *, print_time_s: int = 850) -> SliceResult:
    """A SliceResult backed by a real file, with the numbers a real slice gave.

    850 s / 2.39 cm3 are what the `tee` fixture actually measured through Orca
    2.3.2, so the pure tests and the slicer test are talking about the same
    part.
    """
    gcode = tmp_path / "plate_1.gcode"
    gcode.write_text("; generated by OrcaSlicer\n")
    return SliceResult(
        gcode_path=gcode,
        layer_count=100,
        max_z_mm=20.0,
        filament_mm=1000.0,
        filament_cm3=2.39,
        filament_g=None,
        print_time_s=print_time_s,
        nozzle_mm=0.4,
        material="PLA",
        layer_height_mm=0.2,
    )


