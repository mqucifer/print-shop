def test_the_file_moves_and_the_result_points_at_it(tmp_path: Path) -> None:
    result = a_result(tmp_path)
    original = result.gcode_path
    renamed = name_gcode(result, job_id=str(uuid.uuid4()), part="tee")

    assert not original.exists(), "plate_1.gcode was left behind"
    assert renamed.gcode_path.exists()
    assert renamed.gcode_path.parent == original.parent


def test_re_slicing_a_job_lands_on_its_own_previous_output(tmp_path: Path) -> None:
    """The review gate can route a job back to slice. That must not raise."""
    job_id = str(uuid.uuid4())
    first = name_gcode(a_result(tmp_path), job_id=job_id, part="tee")

    resliced = a_result(tmp_path)
    resliced.gcode_path.write_text("; a second slice\n")
    second = name_gcode(resliced, job_id=job_id, part="tee")

    assert second.gcode_path == first.gcode_path
    assert second.gcode_path.read_text() == "; a second slice\n"


def test_renaming_a_gcode_that_is_not_there_raises(tmp_path: Path) -> None:
    """A slice that produced nothing must not be renamed into a plausible file."""
    result = a_result(tmp_path)
    result.gcode_path.unlink()
    with pytest.raises(FileNotFoundError):
        name_gcode(result, job_id=str(uuid.uuid4()), part="tee")


def test_renaming_preserves_every_other_measurement(tmp_path: Path) -> None:
    result = a_result(tmp_path)
    renamed = name_gcode(result, job_id=str(uuid.uuid4()), part="tee")
    assert renamed.model_dump(exclude={"gcode_path"}) == result.model_dump(
        exclude={"gcode_path"}
    )


