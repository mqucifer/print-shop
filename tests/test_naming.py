@pytest.mark.slicer
@needs_orca
def test_the_settings_come_from_the_gcode_orca_wrote(tmp_path: Path) -> None:
    """The naming fields are a claim about Orca's output. Only Orca settles it.

    These are read out of the settings footer the slicer writes, not out of the
    profiles it was handed — so this fails if Orca changes the format, which is
    exactly when the filename would quietly lose a field.
    """
    profiles = SlicerProfiles(
        machine=MACHINE,
        process=PROCESS,
        filament=FILAMENT if FILAMENT.exists() else None,
        datadir=DATADIR,
    )
    result = slice_model(write_stl("tee", tmp_path), profiles, tmp_path / "out")

    assert result.nozzle_mm == 0.4
    assert result.layer_height_mm == 0.2
    assert result.material == "PLA"

    job_id = str(uuid.uuid4())
    named = name_gcode(result, job_id=job_id, part="tee")
    assert named.gcode_path.name == f"ECC_0.4_tee_PLA0.2_14m_{job_id}.gcode"
    assert job_id_from_filename(named.gcode_path.name) == job_id
